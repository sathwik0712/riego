from sqlalchemy import Column, Integer, String, Float, Boolean, Date, DateTime, ForeignKey, Index, JSON
from sqlalchemy.sql import func
from database import Base


# Farmer profile
class Farmer(Base):
    __tablename__ = "farmers"

    id = Column(Integer, primary_key=True, index=True)
    farmer_id = Column(String, unique=True, nullable=False)          # e.g. "farmer_001"
    name = Column(String, nullable=False)
    phone = Column(String(10), unique=True, nullable=False)          # 10-digit phone
    village = Column(String, nullable=False)
    preferred_language = Column(String, nullable=False, default="en") # "en", "hi", or "kn"
    created_at = Column(DateTime(timezone=True), server_default=func.now())


class Field(Base):
    __tablename__ = "fields"

    # Primary key (auto-incremented integer)
    id = Column(Integer, primary_key=True, index=True)

    # Required farmer ID, linked to farmers table
    farmer_id = Column(String, ForeignKey("farmers.farmer_id"), nullable=False, default="farmer_001")

    # Optional nickname for the field
    nickname = Column(String, nullable=True)

    # Required coordinates
    latitude = Column(Float, nullable=False)
    longitude = Column(Float, nullable=False)

    # Required field size and unit ("acres" or "guntas")
    area = Column(Float, nullable=False)
    area_unit = Column(String, nullable=False)

    # Required crop type
    crop = Column(String, nullable=False)

    # Optional sowing date (null means "not sown yet")
    sowing_date = Column(Date, nullable=True)

    # Required soil and irrigation details
    soil_type = Column(String, nullable=False)
    water_source = Column(String, nullable=False)
    irrigation_method = Column(String, nullable=False)

    # Optional pump flow rate (unit: litres per hour, L/h)
    pump_flow_rate = Column(Float, nullable=True)

    # Optional pump horsepower (HP)
    pump_hp = Column(Float, nullable=True)

    # Source of pump flow rate: "typed", "estimated_from_hp", or "default"
    pump_flow_source = Column(String, nullable=True)

    # Required hardware sensor flag
    has_sensor = Column(Boolean, nullable=False)

    # Optional unique telemetry device ID
    device_id = Column(String, nullable=True, unique=True)

    # SHA-256 hash of the device key (never stored in plain text)
    device_key_hash = Column(String(64), nullable=True)

    # Registration timestamp with timezone (defaults to now)
    registered_at = Column(DateTime(timezone=True), server_default=func.now())


class SensorReading(Base):
    __tablename__ = "sensor_readings"

    # Composite primary key (time, device_id) required for TimescaleDB hypertable
    time = Column(DateTime(timezone=True), primary_key=True, server_default=func.now())
    device_id = Column(String, primary_key=True)

    # Foreign key referencing the associated field
    field_id = Column(Integer, ForeignKey("fields.id"), nullable=False)

    # Telemetry sensor reading
    raw_value = Column(Integer, nullable=False)

    # Moisture percentage (optional, calculated in later steps)
    moisture_percent = Column(Float, nullable=True)

    # Reading source: "sensor" or "manual"
    source = Column(String, nullable=True)


# Weather reading history: one row is saved each time fresh weather is fetched
class WeatherReading(Base):
    __tablename__ = "weather_readings"

    # Composite primary key (recorded_at, field_id) required for TimescaleDB hypertable
    recorded_at = Column(DateTime(timezone=True), primary_key=True, server_default=func.now())
    field_id = Column(Integer, ForeignKey("fields.id"), primary_key=True, nullable=False)

    # Weather telemetry metrics
    temperature_c = Column(Float, nullable=False)
    humidity_percent = Column(Float, nullable=False)
    wind_speed_ms = Column(Float, nullable=False)
    rain_mm_last_hour = Column(Float, nullable=False, default=0.0)
    is_raining = Column(Boolean, nullable=False, default=False)
    description = Column(String, nullable=True)

    # Composite index to optimize retrieving the latest weather readings for a field (newest first)
    __table_args__ = (
        Index("ix_weather_readings_field_recorded_at", field_id, recorded_at.desc()),
    )


# Irrigation recommendations generated by rules or ML models
class Recommendation(Base):
    __tablename__ = "recommendations"

    # Primary key (auto-incremented integer)
    id = Column(Integer, primary_key=True, index=True)

    # Required field ID referencing fields table
    field_id = Column(Integer, ForeignKey("fields.id"), nullable=False)

    # Creation timestamp in UTC
    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)

    # Advice summary and recommended action
    advice_text = Column(String, nullable=False)
    action = Column(String, nullable=False)                          # "water" or "wait"

    # Optional suggested time and duration
    water_at = Column(DateTime(timezone=True), nullable=True)        # time the farmer should water, optional
    duration_minutes = Column(Integer, nullable=True)                # optional

    # Generation source and execution status
    source = Column(String, nullable=False, default="rule")          # "rule" or "ml"
    status = Column(String, nullable=False, default="pending")       # "pending", "done" or "skipped"

    # Composite index on (field_id, created_at DESC)
    __table_args__ = (
        Index("ix_recommendations_field_created_at", field_id, created_at.desc()),
    )


# Logs of actual irrigation events performed on a field
class IrrigationLog(Base):
    __tablename__ = "irrigation_logs"

    # Primary key (auto-incremented integer)
    id = Column(Integer, primary_key=True, index=True)

    # Required field ID referencing fields table
    field_id = Column(Integer, ForeignKey("fields.id"), nullable=False)

    # Irrigation event details
    started_at = Column(DateTime(timezone=True), nullable=False)     # UTC
    duration_minutes = Column(Integer, nullable=False)
    water_liters = Column(Float, nullable=True)                      # optional
    source = Column(String, nullable=False, default="farmer")        # "farmer" or "auto"

    # Event origin: "farmer_tap", "manual_entry", or "sensor_detected"
    event_source = Column(String, nullable=True)

    # Actual watering timestamp in UTC (watering time, which can differ from tap time)
    irrigated_at = Column(DateTime(timezone=True), nullable=True)

    # Optional reference to a recommendation that prompted this irrigation
    recommendation_id = Column(Integer, ForeignKey("recommendations.id"), nullable=True)

    # Record creation timestamp in UTC
    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)

    # Composite index on (field_id, started_at DESC)
    __table_args__ = (
        Index("ix_irrigation_logs_field_started_at", field_id, started_at.desc()),
    )


# Weather forecast snapshots: captures 24h summary and 5-day daily forecast for ML training
class ForecastSnapshot(Base):
    __tablename__ = "forecast_snapshots"

    # Primary key (auto-incremented integer)
    id = Column(Integer, primary_key=True, index=True)

    # Required field ID referencing fields table
    field_id = Column(Integer, ForeignKey("fields.id"), nullable=False, index=True)

    # Fetch timestamp in UTC
    fetched_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False, index=True)

    # 24-hour summary metrics
    rain_next_24h_mm = Column(Float, nullable=True)
    rain_chance_next_24h = Column(Float, nullable=True)
    max_temp_next_24h = Column(Float, nullable=True)

    # 5-day daily forecast summary
    daily_summary = Column(JSON, nullable=True)

    # Composite index on (field_id, fetched_at)
    __table_args__ = (
        Index("ix_forecast_snapshots_field_fetched_at", field_id, fetched_at),
    )


# Authentication tokens for session management
class AuthToken(Base):
    __tablename__ = "auth_tokens"

    # Primary key (auto-incremented integer)
    id = Column(Integer, primary_key=True, index=True)

    # Required farmer ID referencing farmers table
    farmer_id = Column(String, ForeignKey("farmers.farmer_id"), nullable=False, index=True)

    # SHA-256 hash of the bearer token
    token_hash = Column(String(64), unique=True, index=True, nullable=False)

    # Creation timestamp in UTC
    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)

    # Expiration timestamp in UTC (30 days)
    expires_at = Column(DateTime(timezone=True), nullable=False)




